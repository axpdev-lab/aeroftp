// One registration catalog for Settings, NSIS and MSI. Never register a default.
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const data = JSON.parse(fs.readFileSync(new URL('src-tauri/installer/association-registry.json', root), 'utf8'));
const outputs = new Map();
const nsisValue = s => s.replaceAll('"', '$\\"').replaceAll('@EXE@', '$INSTDIR\\AeroFTP.exe').replaceAll('@DIR@', '$INSTDIR');
let nsis = '; Generated by scripts/generate-windows-associations.mjs; do not edit.\n';
for (const group of ['owned', 'archives', 'common']) {
  const values = data.values.filter(v => v.group === group);
  for (const enabled of [true, false]) {
    nsis += `!macro AeroFTP${enabled ? 'Register' : 'Unregister'}_${group}\n`;
    for (const v of values) {
      nsis += enabled
        ? `    ClearErrors\n    WriteRegStr HKCU "${v.key}" "${v.name}" "${nsisValue(v.value)}"\n    IfErrors _aeroftp_registration_failed 0\n`
        : `    !insertmacro AeroFTPDeleteMatchingValue "${v.key}" "${v.name}" "${nsisValue(v.value)}"\n`;
    }
    if (!enabled) {
      const keys = new Set();
      for (const {key} of values) { let k = key; while (k.startsWith('Software\\Classes\\') || k.startsWith('Software\\AeroFTP\\Capabilities')) { keys.add(k); k = k.slice(0, k.lastIndexOf('\\')); } }
      for (const key of [...keys].sort((a,b) => b.split('\\').length - a.split('\\').length)) nsis += `    DeleteRegKey /ifempty HKCU "${key}"\n`;
    }
    nsis += '!macroend\n';
  }
}
outputs.set('src-tauri/installer/associations-generated.nsh', nsis);
const esc = s => s.replaceAll('&','&amp;').replaceAll('"','&quot;').replaceAll('<','&lt;').replaceAll('@EXE@','[INSTALLDIR]aeroftp.exe').replaceAll('@DIR@','[INSTALLDIR]').replaceAll('[INSTALLDIR]\\','[INSTALLDIR]');
// Stable identifiers and GUIDs belong to these persistent feature groups.
// One component per group makes a choice remove exactly that group.
let wix = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-windows-associations.mjs; do not edit. -->\n<?if $(sys.BUILDARCH)="x64" or $(sys.BUILDARCH)="arm64"?>\n<?define Win64 = "yes" ?>\n<?else?>\n<?define Win64 = "no" ?>\n<?endif?>\n<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi"><Fragment>\n';
const groups = [
  ['owned','AeroFTPOwnedAssociations','AeroFTP file formats','449987CB-52DA-4B46-82D7-F9EB2B7038D1'],
  ['archives','AeroFTPArchiveAssociations','Archive formats and Explorer menus','1974D4FC-4A3E-4AAC-8816-3D56CAD68B42'],
];
for (const [group,id,title,guid] of groups) {
  wix += `<DirectoryRef Id="INSTALLDIR"><Component Id="${id}Registry" Guid="${guid}" Win64="$(var.Win64)">\n`;
  wix += `<RegistryValue Root="HKLM" Key="Software\\AeroFTP\\Settings" Name="${group === 'owned' ? 'OwnedFormats' : 'ArchiveFormats'}" Type="integer" Value="1" KeyPath="yes" />\n`;
  for (const v of data.values.filter(v=>v.group===group)) wix += `<RegistryValue Root="HKLM" Key="${v.key}" ${v.name ? `Name="${v.name}"` : ''} Type="string" Value="${esc(v.value)}" />\n`;
  wix += `</Component></DirectoryRef>\n<Feature Id="${id}" Title="${title}" Level="1" AllowAdvertise="no" Absent="allow"><ComponentRef Id="${id}Registry" /><Condition Level="0">AEROFTP_NOASSOC = "1"</Condition></Feature>\n`;
}
wix += '</Fragment></Wix>\n';
outputs.set('src-tauri/installer/associations.wxs', wix);
let stale=false;
for (const [path,content] of outputs) {const url = new URL(path,root); if (process.argv.includes('--check')) {if (!fs.existsSync(url) || fs.readFileSync(url,'utf8') !== content) {console.error(`Stale generated associations: ${path}`); stale=true;}} else fs.writeFileSync(url,content);}
if(stale) process.exitCode=1;
