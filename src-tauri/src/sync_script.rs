fn build_metadata_json(profile: &AerosyncScriptProfile, app_version: &str) -> serde_json::Value {
    let mut map = serde_json::Map::new();
    map.insert(
        "format".to_string(),
        serde_json::Value::String("aerosync-script".to_string()),
    );
    map.insert(
        "format_version".to_string(),
        serde_json::Value::Number(serde_json::Number::from(1)),
    );
    map.insert(
        "generated_by".to_string(),
        serde_json::Value::String(format!("AeroFTP {}", app_version)),
    );
    map.insert(
        "generated_at".to_string(),
        serde_json::Value::String(Utc::now().to_rfc3339()),
    );
    map.insert(
        "profile_id".to_string(),
        serde_json::Value::String(profile.profile.id.clone()),
    );
    map.insert(
        "profile_name".to_string(),
        serde_json::Value::String(profile.profile.name.clone()),
    );
    map.insert(
        "builtin".to_string(),
        serde_json::Value::Bool(profile.profile.builtin),
    );
    if let Ok(v) = serde_json::to_value(&profile.profile.retry_policy) {
        map.insert("retry_policy".to_string(), v);
    }
    if let Ok(v) = serde_json::to_value(&profile.profile.verify_policy) {
        map.insert("verify_policy".to_string(), v);
    }
    map.insert(
        "parallel_streams".to_string(),
        serde_json::Value::Number(serde_json::Number::from(profile.profile.parallel_streams)),
    );
    if let Ok(v) = serde_json::to_value(&profile.profile.compression_mode) {
        map.insert("compression_mode".to_string(), v);
    }
    map.insert(
        "compare_timestamp".to_string(),
        serde_json::Value::Bool(profile.profile.compare_timestamp),
    );
    map.insert(
        "compare_size".to_string(),
        serde_json::Value::Bool(profile.profile.compare_size),
    );
    map.insert(
        "compare_checksum".to_string(),
        serde_json::Value::Bool(profile.profile.compare_checksum),
    );
    serde_json::Value::Object(map)
}

fn direction_to_flag(direction: CompareDirection) -> &'static str {
    match direction {
        CompareDirection::LocalToRemote => "upload",
        CompareDirection::RemoteToLocal => "download",
        CompareDirection::Bidirectional => "both",
    }
}

fn flag_to_direction(flag: &str) -> Option<CompareDirection> {
    match flag {
        "upload" => Some(CompareDirection::LocalToRemote),
        "download" => Some(CompareDirection::RemoteToLocal),
        "both" | "bidirectional" => Some(CompareDirection::Bidirectional),
        _ => None,
    }
}

/// Double-quote a shell token, escaping `\` and `"`.
fn shell_quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            _ => out.push(ch),
        }
    }
    out.push('"');
    out
}

/// PowerShell single-quote a literal.
fn ps1_quote(value: &str) -> String {
    let escaped = value.replace('\'', "''");
    format!("'{}'", escaped)
}

/// Body-safe sh-quote: escape `"`, `$`, backslash so the wrapper
/// template's surrounding double quotes still bind correctly.
fn sh_quote_body(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '$' => out.push_str("\\$"),
            '\\' => out.push_str("\\\\"),
            '`' => out.push_str("\\`"),
            _ => out.push(ch),
        }
    }
    out
}

fn expand_variables(
    body: &str,
    vars: &std::collections::HashMap<String, String>,
    line: usize,
) -> Result<String, ParseError> {
    // CLAUDE-AV-B3-04: scan by `str` slices, never by raw bytes. The prior
    // fallback computed a char length from `(b as char).len_utf8()` on a RAW
    // byte, which for a multi-byte UTF-8 lead byte (e.g. 0xE7) yields the wrong
    // length and slices mid-character, panicking on any non-ASCII literal path
    // in a SYNC/CONNECT line. `find("${")` and slicing at the returned char
    // boundaries is UTF-8-safe.
    let mut out = String::with_capacity(body.len());
    let mut rest = body;
    while let Some(pos) = rest.find("${") {
        out.push_str(&rest[..pos]);
        let after = &rest[pos + 2..];
        if let Some(end) = after.find('}') {
            let name = &after[..end];
            match vars.get(name) {
                Some(v) => out.push_str(v),
                None => {
                    return Err(ParseError::UndefinedVariable {
                        line,
                        name: name.to_string(),
                    });
                }
            }
            rest = &after[end + 1..];
        } else {
            // No closing brace: emit the literal "${" and keep scanning after it
            // (preserves the pre-fix behavior for an unterminated variable).
            out.push_str("${");
            rest = after;
        }
    }
    out.push_str(rest);
    Ok(out)
}

/// Collect a logical line that may span multiple physical lines via
/// trailing `\` continuations. Advances `idx` past the joined region.
fn collect_continued_line(first: &str, lines: &[&str], idx: &mut usize) -> String {
    let mut joined = first.trim().to_string();
    *idx += 1;
    loop {
        if joined.ends_with('\\') {
            joined.pop(); // strip the trailing backslash
            joined.push(' ');
            if *idx >= lines.len() {
                break;
            }
            let next = lines[*idx].trim();
            joined.push_str(next);
            *idx += 1;
            continue;
        }
        break;
    }
    joined
}

fn parse_connect(body: &str, line: usize) -> Result<(Option<String>, Option<String>), ParseError> {
    let tokens =
        tokenize(body, line).map_err(|message| ParseError::MalformedConnect { line, message })?;
    let mut it = tokens.into_iter().peekable();
    let mut profile: Option<String> = None;
    let mut url: Option<String> = None;
    while let Some(tok) = it.next() {
        match tok.as_str() {
            "--profile" => {
                let v = it.next().ok_or_else(|| ParseError::MalformedConnect {
                    line,
                    message: "--profile expects a value".to_string(),
                })?;
                profile = Some(v);
            }
            other if !other.starts_with('-') && profile.is_none() && url.is_none() => {
                // Treat the first positional token as a URL when no
                // --profile is given.
                url = Some(other.to_string());
            }
            _ => {}
        }
    }
    if profile.is_none() && url.is_none() {
        return Err(ParseError::MalformedConnect {
            line,
            message: "expected --profile <name> or a URL".to_string(),
        });
    }
    Ok((profile, url))
}

struct ParsedSyncLine {
    path_pair: (String, String),
    direction: CompareDirection,
    delete_orphans: bool,
    dry_run: bool,
    track_renames: bool,
    skip_matching: bool,
    resync: bool,
    watch: bool,
    conflict_mode: Option<String>,
    exclude_patterns: Vec<String>,
}

fn parse_sync(body: &str, line: usize) -> Result<ParsedSyncLine, ParseError> {
    let tokens =
        tokenize(body, line).map_err(|message| ParseError::MalformedSync { line, message })?;
    let mut positional: Vec<String> = Vec::new();
    let mut direction: Option<CompareDirection> = None;
    let mut delete_orphans = false;
    let mut dry_run = false;
    let mut track_renames = false;
    let mut skip_matching = false;
    let mut resync = false;
    let mut watch = false;
    let mut conflict_mode: Option<String> = None;
    let mut exclude_patterns: Vec<String> = Vec::new();
    let mut it = tokens.into_iter().peekable();
    while let Some(tok) = it.next() {
        match tok.as_str() {
            "--direction" => {
                let v = it.next().ok_or_else(|| ParseError::MalformedSync {
                    line,
                    message: "--direction expects a value".to_string(),
                })?;
                direction =
                    Some(
                        flag_to_direction(&v).ok_or_else(|| ParseError::MalformedSync {
                            line,
                            message: format!("unknown direction '{}'", v),
                        })?,
                    );
            }
            "--delete" => delete_orphans = true,
            "--dry-run" => dry_run = true,
            "--track-renames" => track_renames = true,
            "--skip-matching" => skip_matching = true,
            "--resync" => resync = true,
            "--watch" => watch = true,
            "--conflict-mode" => {
                let v = it.next().ok_or_else(|| ParseError::MalformedSync {
                    line,
                    message: "--conflict-mode expects a value".to_string(),
                })?;
                if !CONFLICT_MODES.contains(&v.as_str()) {
                    return Err(ParseError::MalformedSync {
                        line,
                        message: format!("unknown conflict mode '{}'", v),
                    });
                }
                conflict_mode = Some(v);
            }
            "--exclude" | "-e" => {
                let v = it.next().ok_or_else(|| ParseError::MalformedSync {
                    line,
                    message: "--exclude expects a pattern".to_string(),
                })?;
                exclude_patterns.push(v);
            }
            other if other.starts_with("--") => {
                // Forward-compat: ignore unknown long flags but try to
                // also consume their value if it does not look like a
                // flag itself.
                if let Some(next) = it.peek() {
                    if !next.starts_with('-') {
                        let _ = it.next();
                    }
                }
            }
            _ => positional.push(tok),
        }
    }
    if positional.len() < 2 {
        return Err(ParseError::MalformedSync {
            line,
            message: format!(
                "expected local + remote path arguments, got {}",
                positional.len()
            ),
        });
    }
    let direction = direction.ok_or_else(|| ParseError::MalformedSync {
        line,
        message: "missing --direction".to_string(),
    })?;
    let local = positional[0].clone();
    let remote = positional[1].clone();
    Ok(ParsedSyncLine {
        path_pair: (local, remote),
        direction,
        delete_orphans,
        dry_run,
        track_renames,
        skip_matching,
        resync,
        watch,
        conflict_mode,
        exclude_patterns,
    })
}

/// Tokenise a shell-style command body. Supports double and single
/// quotes and `\` escapes inside double-quoted regions.
fn tokenize(body: &str, _line: usize) -> Result<Vec<String>, String> {
    let mut out: Vec<String> = Vec::new();
    let mut current = String::new();
    let mut in_double = false;
    let mut in_single = false;
    let mut escape = false;
    let mut has_token = false;
    for ch in body.chars() {
        if escape {
            current.push(ch);
            escape = false;
            has_token = true;
            continue;
        }
        match ch {
            '\\' if in_double => {
                escape = true;
            }
            '"' if !in_single => {
                in_double = !in_double;
                has_token = true;
            }
            '\'' if !in_double => {
                in_single = !in_single;
                has_token = true;
            }
            c if c.is_whitespace() && !in_double && !in_single => {
                if has_token {
                    out.push(std::mem::take(&mut current));
                    has_token = false;
                }
            }
            c => {
                current.push(c);
                has_token = true;
            }
        }
    }
    if in_double || in_single {
        return Err("unterminated quoted token".to_string());
    }
    if has_token {
        out.push(current);
    }
    Ok(out)
}

